#!/usr/bin/env bash

# Frigate OCI Script Updater for Proxmox VE 9.1+
# Automates the lifecycle of updating native OCI container templates.

set -eo pipefail

# Colors
GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

# Helper log functions
log_step() { echo -e "${BLUE}[STEP]${NC} $1"; }
log_success() { echo -e "${GREEN}[DONE]${NC} $1"; }
log_warn() { echo -e "${YELLOW}[WARN]${NC} $1"; }
log_info() { echo -e "${CYAN}[INFO]${NC} $1"; }
error_exit() { echo -e "${RED}[ERROR]${NC} $1" >&2; exit 1; }

get_container_ip() {
    local ctid="$1"
    local ip=""
    ip=$(lxc-info -n "$ctid" -i -H 2>/dev/null | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+' | grep -v '^127\.' | head -n 1 || echo "")
    if [ -z "$ip" ]; then
        ip=$(pvesh get "/nodes/localhost/lxc/${ctid}/interfaces" --output-format json 2>/dev/null | python3 -c "import sys, json
try:
    ifaces = json.load(sys.stdin)
    for iface in ifaces:
        for inet in iface.get('inet-addresses', []):
            addr = inet.get('ip', '')
            if addr and not addr.startswith('127.') and '.' in addr:
                print(addr)
                sys.exit(0)
except Exception:
    pass
" 2>/dev/null || echo "")
    fi
    if [ -z "$ip" ]; then
        ip=$(pct exec "$ctid" -- ip -4 addr show eth0 2>/dev/null | awk '/inet / {print $2}' | cut -d/ -f1 | head -n 1 || echo "")
    fi
    if [ -z "$ip" ]; then
        ip=$(pct exec "$ctid" -- hostname -I 2>/dev/null | awk '{print $1}' || echo "")
    fi
    echo "$ip"
}

# Rewrite the network hookscript when it was generated by an older installer.
# Those versions over-escaped the heredoc, so the script exited immediately and
# never configured the container network.
repair_network_hookscript() {
    local hookscript_path="/var/lib/vz/snippets/ct${CT_ID}-network.sh"
    local net0 net_ip net_gw net_cmd template

    if [ ! -f "$hookscript_path" ]; then
        return 0
    fi

    if grep -q 'VMID="\$1"' "$hookscript_path" 2>/dev/null; then
        log_success "Network hookscript already up to date."
        return 0
    fi

    if [ "$DRY_RUN" = true ]; then
        log_info "[DRY RUN] Would regenerate $hookscript_path with working escaping"
        return 0
    fi

    net0=$(grep "^net0:" "$LXC_CONF" | head -n 1 | cut -d: -f2- || echo "")
    net_ip=$(echo "$net0" | tr ',' '\n' | awk -F= '/^ip=/ {print $2; exit}')
    net_gw=$(echo "$net0" | tr ',' '\n' | awk -F= '/^gw=/ {print $2; exit}')

    if [ "$net_ip" = "dhcp" ] || [ -z "$net_ip" ]; then
        net_cmd=""
    else
        net_cmd="nsenter -t \"\$CT_PID\" -n ip addr replace $net_ip dev eth0 2>/dev/null
        nsenter -t \"\$CT_PID\" -n ip route replace default via $net_gw 2>/dev/null"
    fi

    template=$(cat <<'HOOKEOF'
#!/bin/bash
# Proxmox hookscript: configure network and flush IPv6 for CT __CT_ID__

VMID="$1"
PHASE="$2"

if [ "$VMID" != "__CT_ID__" ] || [ "$PHASE" != "post-start" ]; then
    exit 0
fi

# Run in background via setsid to release PVE startup task immediately
setsid bash -c '
    for i in {1..50}; do
        CT_PID=$(lxc-info -n __CT_ID__ -p -H 2>/dev/null)
        if [ -n "$CT_PID" ]; then
            break
        fi
        sleep 0.05
    done
    if [ -n "$CT_PID" ]; then
        echo "ct__CT_ID__-network: configuring network inside PID $CT_PID..."
        nsenter -t "$CT_PID" -n sysctl -w net.ipv6.conf.all.disable_ipv6=1
        nsenter -t "$CT_PID" -n sysctl -w net.ipv6.conf.default.disable_ipv6=1
        nsenter -t "$CT_PID" -n sysctl -w net.ipv6.conf.eth0.disable_ipv6=1
        nsenter -t "$CT_PID" -n ip link set lo up
        nsenter -t "$CT_PID" -n ip link set eth0 up
        __NET_CMD__
        echo "ct__CT_ID__-network: network configured successfully"
    fi
' > /var/log/ct__CT_ID__-network.log 2>&1 &

exit 0
HOOKEOF
)
    template=${template//__CT_ID__/$CT_ID}
    template=${template//__NET_CMD__/$net_cmd}
    printf '%s\n' "$template" > "$hookscript_path"
    chmod +x "$hookscript_path"
    log_success "Regenerated network hookscript at $hookscript_path"
}

# Install the host-managed DHCP helper used by the auto-restart override.
# pct start runs this after the hookscript; a systemd restart skips that
# path, so the override calls the helper as well. It waits for the normal
# DHCP client first, then only starts one if the interface still has no IP.
install_dhcp_helper() {
    cat > /usr/local/bin/frigate-ct-dhcp <<'PERLEOF'
#!/usr/bin/perl
use strict;
use warnings;
use PVE::LXC;
use PVE::LXC::Config;

$| = 1;

my $vmid = shift @ARGV;
exit 0 if !defined($vmid) || $vmid !~ /^\d+$/;

my $conf = eval { PVE::LXC::Config->load_config($vmid) };
exit 0 if !$conf;

my @managed;
for my $k (sort keys %$conf) {
    next if $k !~ /^net\d+$/;
    my $d = eval { PVE::LXC::Config->parse_lxc_network($conf->{$k}) };
    next if !$d || !$d->{'host-managed'} || !$d->{name};
    push @managed, [$d->{name}, 4] if defined($d->{ip}) && $d->{ip} eq 'dhcp';
    push @managed, [$d->{name}, 6] if defined($d->{ip6}) && $d->{ip6} eq 'dhcp';
}
exit 0 if !@managed;

# Give pct start's own DHCP client time to run first. On a systemd
# auto-restart that path is bypassed, so this is the only client that runs.
sleep 5;

my $pid;
for (1 .. 5) {
    ($pid) = eval { PVE::LXC::open_lxc_pid($vmid) };
    last if $pid;
    sleep 1;
}
exit 0 if !$pid;

my $rootdir = "/proc/$pid/root";

for my $item (@managed) {
    my ($eth, $version) = @$item;
    my $pattern = $version == 4 ? qr/\binet\s/ : qr/\binet6\s+.*\bscope global\b/;
    my $out = '';
    if (open my $fh, '-|', 'nsenter', '-t', $pid, '-n', 'ip', "-$version", 'addr', 'show', 'dev', $eth) {
        local $/;
        $out = <$fh> // '';
        close $fh;
    }
    next if $out =~ $pattern;

    print "starting host-managed DHCPv$version for $eth\n";
    eval { PVE::LXC::manage_dhclient('start', $vmid, $version, $eth, $rootdir) };
    print "DHCPv$version failed: $@" if $@;
}

exit 0;
PERLEOF
    chmod +x /usr/local/bin/frigate-ct-dhcp
}

# Set terminal title
echo -ne "\033]0;Frigate OCI Script Updater\007"

echo -e "${GREEN}"
echo "============================================="
echo "         Frigate OCI Script Updater          "
echo "============================================="
echo -e "${NC}"

# System checks
if [ "$(id -u)" -ne 0 ]; then
    error_exit "This script must be run as root on your Proxmox VE host."
fi

# Parse arguments
CT_ID=""
VERSION=""
TEMPLATE_STORAGE=""
DRY_RUN=false

while [[ $# -gt 0 ]]; do
    case "$1" in
        -i|--id|--container)
            CT_ID="$2"
            shift 2
            ;;
        -v|--version)
            VERSION="$2"
            shift 2
            ;;
        -t|--template-storage)
            TEMPLATE_STORAGE="$2"
            shift 2
            ;;
        -d|--dry-run)
            DRY_RUN=true
            shift
            ;;
        *)
            if [[ "$1" =~ ^[0-9]+$ ]] && [ -z "$CT_ID" ]; then
                CT_ID="$1"
            elif [ -z "$VERSION" ] && [[ ! "$1" =~ ^- ]]; then
                VERSION="$1"
            fi
            shift
            ;;
    esac
done

# Fallback to interactive prompts if not provided
if [ -z "$CT_ID" ]; then
    read -p "Enter Frigate Container ID: " CT_ID
fi

if [ -z "$TEMPLATE_STORAGE" ]; then
    TEMPLATE_STORAGES=$(pvesm status -content vztmpl 2>/dev/null | awk 'NR>1 {print $1}')
    if echo "$TEMPLATE_STORAGES" | grep -q "^local$"; then
        TEMPLATE_STORAGE="local"
    else
        TEMPLATE_STORAGE=$(echo "$TEMPLATE_STORAGES" | head -n 1)
    fi
fi

if [ -z "$VERSION" ]; then
    read -p "Enter new Frigate Version Tag (e.g., 0.17.2, or press Enter for latest stable): " VERSION
    VERSION=${VERSION:-latest}
fi

if [ "$VERSION" = "latest" ]; then
    log_step "Fetching latest stable Frigate release tag from GitHub..."
    LATEST_TAG=$(curl -s https://api.github.com/repos/blakeblackshear/frigate/releases/latest | python3 -c "import sys, json; print(json.load(sys.stdin).get('tag_name', '').lstrip('v'))" 2>/dev/null || echo "")
    if [ -n "$LATEST_TAG" ]; then
        VERSION="$LATEST_TAG"
        log_success "Found latest stable version: $VERSION"
    else
        log_warn "Failed to fetch latest version from GitHub. Defaulting to 0.17.2"
        VERSION="0.17.2"
    fi
fi

# Verify container exists
if ! pct status "$CT_ID" &>/dev/null; then
    error_exit "Container ID $CT_ID does not exist on this Proxmox host."
fi

# Pull the new template FIRST before making any destructive changes
FRIGATE_IMAGE="ghcr.io/blakeblackshear/frigate:$VERSION"
SAFE_IMG_NAME=$(echo "$FRIGATE_IMAGE" | tr '/:' '-')
# Do NOT append .tar to filename as Proxmox does it automatically
OCI_TEMPLATE_NAME="${SAFE_IMG_NAME}"

log_step "Pulling OCI image: $FRIGATE_IMAGE..."
log_info "Initiating pull through Proxmox OCI Registry API..."

# Check if template is already cached on host to bypass duplicate pull
# We query the storage path using a dummy volume ID with a standard extension (.tar.gz)
# because some Proxmox storage plugins fail to parse volume IDs ending in .tar via 'pvesm path'.
TEMPLATE_DIR_PATH=$(pvesm path "${TEMPLATE_STORAGE}:vztmpl/dummy.tar.gz" 2>/dev/null || echo "")
if [ -n "$TEMPLATE_DIR_PATH" ]; then
    TEMPLATE_PATH="$(dirname "$TEMPLATE_DIR_PATH")/${OCI_TEMPLATE_NAME}.tar"
else
    STORAGE_DIR=$(grep -A 5 "^dir: ${TEMPLATE_STORAGE}" /etc/pve/storage.cfg 2>/dev/null | awk '/path / {print $2}' | head -n 1 || echo "")
    if [ -n "$STORAGE_DIR" ]; then
        TEMPLATE_PATH="${STORAGE_DIR}/template/cache/${OCI_TEMPLATE_NAME}.tar"
    else
        TEMPLATE_PATH=""
    fi
fi
PULL_REQUIRED=true

if [ -n "$TEMPLATE_PATH" ] && [ -f "$TEMPLATE_PATH" ]; then
    log_success "OCI Image is already cached on host at: $TEMPLATE_PATH"
    log_info "Skipping download and using existing template."
    PULL_REQUIRED=false
fi

if [ "$PULL_REQUIRED" = true ]; then
    if [ "$DRY_RUN" = true ]; then
        log_info "[DRY RUN] Would pull OCI image $FRIGATE_IMAGE and cache as ${TEMPLATE_STORAGE}:vztmpl/${OCI_TEMPLATE_NAME}.tar"
    else
        # Remove any existing/incomplete file at the template path to prevent "refusing to override existing file" error
        if [ -n "$TEMPLATE_PATH" ]; then
            if [ -f "$TEMPLATE_PATH" ]; then
                log_warn "Removing existing/incomplete template file at $TEMPLATE_PATH to allow a fresh pull..."
                rm -f "$TEMPLATE_PATH"
            fi
            rm -f "${TEMPLATE_PATH}.tmp."* 2>/dev/null || true
        fi

        PULL_SUCCESS=false
        PVE_OUT=$(pvesh create "/nodes/localhost/storage/${TEMPLATE_STORAGE}/oci-registry-pull" \
            --reference "$FRIGATE_IMAGE" \
            --filename "$OCI_TEMPLATE_NAME" \
            --output-format json 2>/dev/null || echo "")

        UPID=$(echo "$PVE_OUT" | python3 -c 'import sys, json; print(json.load(sys.stdin))' 2>/dev/null || echo "")

        if [ -z "$UPID" ] || [[ ! "$UPID" =~ ^UPID: ]]; then
            # Fallback if JSON parsing failed or stdout returned raw string
            UPID=$(echo "$PVE_OUT" | grep -o 'UPID:[^[:space:]"]*' | head -n 1 || echo "")
        fi

        if [ -n "$UPID" ] && [[ "$UPID" =~ ^UPID: ]]; then
            log_info "Task started with UPID: $UPID. Downloading..."

            # Poll task for completion
            while true; do
                task_status_json=$(pvesh get "/nodes/localhost/tasks/${UPID}/status" --output-format json 2>/dev/null || echo "")
                if [ -n "$task_status_json" ]; then
                    status=$(echo "$task_status_json" | python3 -c 'import sys, json; print(json.load(sys.stdin).get("status", "running"))' 2>/dev/null || echo "running")
                    exitstatus=$(echo "$task_status_json" | python3 -c 'import sys, json; print(json.load(sys.stdin).get("exitstatus", ""))' 2>/dev/null || echo "")
                else
                    status="running"
                    exitstatus=""
                fi
                
                if [ "$status" = "stopped" ]; then
                    echo ""
                    if [ "$exitstatus" = "OK" ]; then
                        log_success "OCI Image pulled and cached successfully."
                        PULL_SUCCESS=true
                        break
                    else
                        log_warn "Proxmox API pull task exited with: $exitstatus"
                        log_info "Task details:"
                        pvesh get "/nodes/localhost/tasks/${UPID}/log" --output-format text 2>/dev/null | tail -n 8 || true
                        break
                    fi
                fi
                echo -n "."
                sleep 3
            done
        else
            log_warn "Could not initiate pull through Proxmox API ($PVE_OUT)"
        fi

        # Fallback to direct skopeo pull with local storage TMPDIR buffering if Proxmox API pull failed
        if [ "$PULL_SUCCESS" = false ]; then
            if command -v skopeo &>/dev/null && [ -n "$TEMPLATE_PATH" ]; then
                log_info "Attempting direct download with skopeo using storage temp buffering..."
                STORAGE_TMP="$(dirname "$TEMPLATE_PATH")/tmp"
                mkdir -p "$STORAGE_TMP"
                rm -f "${TEMPLATE_PATH}.tmp."* 2>/dev/null || true
                
                if TMPDIR="$STORAGE_TMP" skopeo copy --override-os linux --override-arch amd64 "docker://${FRIGATE_IMAGE}" "oci-archive:${TEMPLATE_PATH}"; then
                    rm -rf "$STORAGE_TMP"
                    log_success "OCI Image pulled and cached successfully via direct skopeo."
                    PULL_SUCCESS=true
                else
                    rm -rf "$STORAGE_TMP"
                    error_exit "Direct skopeo pull failed. Upgrade aborted. Your container is untouched."
                fi
            else
                error_exit "OCI pull task failed. Upgrade aborted. Your container is untouched."
            fi
        fi
    fi
fi

# Parse resource configurations
LXC_CONF="/etc/pve/lxc/${CT_ID}.conf"
log_step "Parsing current container configuration..."
CT_HOSTNAME=$(grep "^hostname:" "$LXC_CONF" | head -n 1 | cut -d: -f2- | xargs || echo "frigate-update-temp")
CT_CORES=$(grep "^cores:" "$LXC_CONF" | head -n 1 | cut -d: -f2- | xargs || echo "4")
CT_RAM=$(grep "^memory:" "$LXC_CONF" | head -n 1 | cut -d: -f2- | xargs || echo "4096")
CT_SWAP=$(grep "^swap:" "$LXC_CONF" | head -n 1 | cut -d: -f2- | xargs || echo "512")
CT_UNPRIV=$(grep "^unprivileged:" "$LXC_CONF" | head -n 1 | cut -d: -f2- | xargs || echo "1")

OLD_ROOTFS=$(grep "^rootfs:" "$LXC_CONF" | head -n 1 | cut -d: -f2- | xargs)
CT_STORAGE=$(echo "$OLD_ROOTFS" | cut -d: -f1)
CT_DISK_SIZE=$(echo "$OLD_ROOTFS" | grep -o "size=[^,]*" | head -n 1 | cut -d= -f2 | tr -d 'Gg')
CT_DISK_SIZE=${CT_DISK_SIZE:-10}

log_info "Configuration loaded: Hostname=$CT_HOSTNAME, Cores=$CT_CORES, RAM=$CT_RAM, Storage=$CT_STORAGE, DiskSize=${CT_DISK_SIZE}G"

# Allocate temporary container ID
TEMP_ID=$(pvesh get /cluster/nextid 2>/dev/null | python3 -c 'import sys, json; print(json.load(sys.stdin))' 2>/dev/null || pvesh get /cluster/nextid --output-format text | awk '{print $NF}' || echo "")
if [ -z "$TEMP_ID" ] || [ "$TEMP_ID" = "$CT_ID" ]; then
    TEMP_ID=$((CT_ID + 100))
    while pct status "$TEMP_ID" &>/dev/null; do
        TEMP_ID=$((TEMP_ID + 1))
    done
fi

# Take a safety snapshot on active container. The timestamp keeps the name
# unique so a repeat update to the same version still gets a fresh snapshot
# instead of matching the previous one and being skipped.
SNAPSHOT_SUFFIX="$(date +%Y%m%d_%H%M%S)"
CLEAN_VERSION=$(echo "$VERSION" | tr '.-' '__')
# Keep the whole name inside Proxmox's 40 character snapshot name limit,
# leaving room for the "pre_to_" prefix and the timestamp suffix.
CLEAN_VERSION=${CLEAN_VERSION:0:$((40 - 7 - 1 - ${#SNAPSHOT_SUFFIX}))}
SNAPSHOT_NAME="pre_to_${CLEAN_VERSION}_${SNAPSHOT_SUFFIX}"
log_step "Taking safety snapshot: $SNAPSHOT_NAME..."
if grep -qF "[pre_to_${CLEAN_VERSION}" "$LXC_CONF" 2>/dev/null; then
    log_info "Keeping existing snapshot from a previous update to $VERSION and taking a fresh one."
fi
if [ "$DRY_RUN" = true ]; then
    log_info "[DRY RUN] Would create snapshot '$SNAPSHOT_NAME' for container $CT_ID"
else
    if pct snapshot "$CT_ID" "$SNAPSHOT_NAME" --description "Before update to $VERSION"; then
        log_success "Snapshot $SNAPSHOT_NAME created."
    else
        log_warn "Failed to create snapshot. Proceeding without safety rollback point."
    fi
fi

# Stop existing container if running
WAS_RUNNING=false
if pct status "$CT_ID" | grep -q "running"; then
    WAS_RUNNING=true
    log_step "Stopping container $CT_ID..."
    if [ "$DRY_RUN" = true ]; then
        log_info "[DRY RUN] Would stop container $CT_ID"
    else
        pct stop "$CT_ID"
    fi
fi

# Create temporary container
log_step "Creating temporary container $TEMP_ID from new template..."
if [ "$DRY_RUN" = true ]; then
    log_info "[DRY RUN] Would create temporary container $TEMP_ID using template ${TEMPLATE_STORAGE}:vztmpl/${OCI_TEMPLATE_NAME}.tar"
else
    pct create "$TEMP_ID" "${TEMPLATE_STORAGE}:vztmpl/${OCI_TEMPLATE_NAME}.tar" \
        --hostname "frigate-update-temp" \
        --cores 1 \
        --memory 512 \
        --swap 512 \
        --rootfs "${CT_STORAGE}:${CT_DISK_SIZE}" \
        --net0 "name=eth0,bridge=vmbr0,ip=dhcp" \
        --ostype unmanaged \
        --unprivileged "$CT_UNPRIV" || error_exit "Failed to create temporary container."
fi

# Mount both containers
if [ "$DRY_RUN" = true ]; then
    log_info "[DRY RUN] Would mount container $CT_ID and $TEMP_ID"
else
    log_step "Mounting filesystems..."
    pct mount "$CT_ID" || error_exit "Failed to mount target container."
    pct mount "$TEMP_ID" || { pct unmount "$CT_ID"; pct destroy "$TEMP_ID"; error_exit "Failed to mount source container."; }
fi

M_OLD="/var/lib/lxc/${CT_ID}/rootfs"
M_NEW="/var/lib/lxc/${TEMP_ID}/rootfs"

# Parse mount configs for excludes
excludes=()
# Parse standard Proxmox mount points (mpN)
while IFS= read -r line; do
    [[ "$line" =~ ^mp[0-9]+: ]] || continue
    cpath=""
    if [[ "$line" =~ ,mp=([^,]+) ]]; then
        cpath="${BASH_REMATCH[1]}"
    elif [[ "$line" =~ mp=([^,]+) ]]; then
        cpath="${BASH_REMATCH[1]}"
    fi
    [[ -n "$cpath" ]] || continue
    rel="${cpath#/}"
    excludes+=( --exclude="/${rel}" --exclude="/${rel%/}/" )
done < <(grep -E '^mp[0-9]+:' "$LXC_CONF" || true)

# Parse low-level lxc.mount.entry
while IFS= read -r line; do
    [[ "$line" =~ ^lxc\.mount\.entry: ]] || continue
    fields=($line)
    guest_path="${fields[2]}"
    [[ -n "$guest_path" ]] || continue
    rel="${guest_path#/}"
    excludes+=( --exclude="/${rel}" --exclude="/${rel%/}/" )
done < <(grep -E '^lxc\.mount\.entry:' "$LXC_CONF" || true)

# Sync files
log_step "Syncing files from new template to active container..."
log_info "Excludes: ${excludes[*]}"
if [ "$DRY_RUN" = true ]; then
    log_info "[DRY RUN] Would sync files from temporary container mount to active container mount using rsync"
else
    rsync -aHAX --delete "${excludes[@]}" "${M_NEW}/" "${M_OLD}/"
    log_success "Sync completed successfully."
fi

# Unmount filesystems
if [ "$DRY_RUN" = true ]; then
    log_info "[DRY RUN] Would unmount filesystems for container $TEMP_ID and $CT_ID"
else
    log_step "Unmounting filesystems..."
    pct unmount "$TEMP_ID" || true
    pct unmount "$CT_ID" || true
fi

# Sync entrypoint configuration if changed
if [ "$DRY_RUN" = true ]; then
    log_info "[DRY RUN] Would check and sync entrypoint config between temporary container $TEMP_ID and active container $CT_ID"
else
    NEW_EP=$(pct config "$TEMP_ID" | grep -a "^entrypoint:" | head -n 1 | cut -d: -f2- | xargs || echo "")
    OLD_EP=$(pct config "$CT_ID" | grep -a "^entrypoint:" | head -n 1 | cut -d: -f2- | xargs || echo "")
    if [ -n "$NEW_EP" ] && [ "$NEW_EP" != "$OLD_EP" ]; then
        log_step "Syncing entrypoint configuration..."
        pct set "$CT_ID" --entrypoint "$NEW_EP"
    elif [ -z "$NEW_EP" ] && [ -n "$OLD_EP" ]; then
        log_step "Clearing entrypoint configuration..."
        pct set "$CT_ID" --delete entrypoint
    fi
fi

# Destroy temporary container
log_step "Destroying temporary container $TEMP_ID..."
if [ "$DRY_RUN" = true ]; then
    log_info "[DRY RUN] Would destroy temporary container $TEMP_ID"
else
    pct destroy "$TEMP_ID" || log_warn "Failed to destroy temporary container."
fi

# Install/refresh the host-managed DHCP helper before the override uses it.
if [ "$DRY_RUN" = true ]; then
    log_info "[DRY RUN] Would install /usr/local/bin/frigate-ct-dhcp"
else
    log_step "Installing host-managed DHCP helper..."
    install_dhcp_helper
fi

# Configure systemd auto-restart override for native OCI lifecycle
log_step "Ensuring container auto-restart service override is configured..."
if [ "$DRY_RUN" = true ]; then
    log_info "[DRY RUN] Would create systemd override at /etc/systemd/system/pve-container@${CT_ID}.service.d/override.conf"
else
    OVERRIDE_DIR="/etc/systemd/system/pve-container@${CT_ID}.service.d"
    mkdir -p "$OVERRIDE_DIR"
    cat > "${OVERRIDE_DIR}/override.conf" << EOF
[Service]
Restart=always
RestartSec=2s
# pct start runs the network hookscript, but a systemd restart relaunches
# lxc-start directly. Run the same post-start hook here and make sure a
# host-managed DHCP client starts if the normal pct path was skipped.
ExecStartPost=/bin/sh -c 'test -x /var/lib/vz/snippets/ct%i-network.sh && /var/lib/vz/snippets/ct%i-network.sh %i post-start; setsid /usr/local/bin/frigate-ct-dhcp %i >>/var/log/ct%i-network.log 2>&1 &'
EOF
    systemctl daemon-reload
    log_success "Auto-restart override configured for CT ${CT_ID}"
fi

# Repair the network hookscript written by older installers
log_step "Checking network hookscript..."
repair_network_hookscript

# Start updated container
if [ "$WAS_RUNNING" = true ]; then
    log_step "Starting updated container $CT_ID..."
    if [ "$DRY_RUN" = true ]; then
        log_info "[DRY RUN] Would start container $CT_ID"
    else
        pct start "$CT_ID" || log_warn "Failed to start container automatically. Try running 'pct start $CT_ID' manually."
    fi
fi

# Update Proxmox summary dashboard notes
log_step "Updating Proxmox summary dashboard..."
IP_ADDRESS=""
# Wait up to 10 seconds for IP address allocation if container started successfully
if [ "$DRY_RUN" = false ] && pct status "$CT_ID" | grep -q "running"; then
    for i in {1..10}; do
        IP_ADDRESS=$(get_container_ip "$CT_ID")
        if [ -n "$IP_ADDRESS" ]; then
            break
        fi
        sleep 1
    done
fi
IP_ADDRESS=${IP_ADDRESS:-"<IP_ADDRESS>"}

# Read details for dashboard
GPU_TYPE="none"
if grep -q "nvidia" "$LXC_CONF"; then
    GPU_TYPE="nvidia"
elif grep -q "render" "$LXC_CONF"; then
    GPU_TYPE="intel/amd/vaapi"
fi

CORAL_LINE=""
if grep -q "apex" "$LXC_CONF"; then
    CORAL_LINE="- Coral Detector: PCIe\\n"
elif grep -q "usb" "$LXC_CONF"; then
    CORAL_LINE="- Coral Detector: USB\\n"
fi

# Detect bind mounts
CONFIG_VAL=$(grep "lxc.mount.entry" "$LXC_CONF" | grep -i "config " | head -n 1 || echo "")
MEDIA_VAL=$(grep "lxc.mount.entry" "$LXC_CONF" | grep -i "media/frigate " | head -n 1 || echo "")

HOST_CONFIG_PATH=$(echo "$CONFIG_VAL" | awk '{print $2}' | head -n 1 || echo "")
HOST_CONFIG_PATH=${HOST_CONFIG_PATH:-"/opt/frigate/config"}

HOST_MEDIA_PATH=$(echo "$MEDIA_VAL" | awk '{print $2}' | head -n 1 || echo "")
HOST_MEDIA_PATH=${HOST_MEDIA_PATH:-"/opt/frigate/media"}

MOUNT_LINE=""
while IFS= read -r line; do
    [ -n "$line" ] || continue
    c_host=$(echo "$line" | awk '{print $2}')
    c_cont=$(echo "$line" | awk '{print $3}')
    if [ -n "$c_host" ] && [ -n "$c_cont" ]; then
        c_clean_cont=$(echo "$c_cont" | sed 's/^\///')
        MOUNT_LINE="${MOUNT_LINE}- External Mount: ${c_host} -> /${c_clean_cont}\\n"
    fi
done < <(grep "lxc.mount.entry" "$LXC_CONF" | grep -vE "config |media/frigate |/dev/bus/usb" || true)

DESCRIPTION=$(echo -e "# Frigate OCI Script

**Quick Access**
| Service | URL |
| :--- | :--- |
| Web UI & API (Unauthenticated) | http://${IP_ADDRESS}:5000 |
| Web UI & API (Recommended) | https://${IP_ADDRESS}:8971 |
| go2rtc API | http://${IP_ADDRESS}:1984 |

*Note: Port 8971 is the secure WebUI and API port and is recommended to be used in every case. Port 5000 is unauthenticated.*

**Hardware Profile**
- GPU Acceleration: ${GPU_TYPE}
${CORAL_LINE}- Resources: ${CT_RAM}MB RAM / ${CT_CORES} CPU Cores

**File Locations**
- Configuration: ${HOST_CONFIG_PATH}/config.yml
- Media Storage: ${HOST_MEDIA_PATH}
${MOUNT_LINE}
---
GitHub: [saihgupr/frigate-oci-script](https://github.com/saihgupr/frigate-oci-script)

Support: [Buy me a coffee](https://ko-fi.com/saihgupr)")

if [ "$DRY_RUN" = true ]; then
    log_info "[DRY RUN] Would update dashboard notes for container $CT_ID to:"
    echo "$DESCRIPTION" | sed 's/^/  /'
else
    if pct set "$CT_ID" --description "$DESCRIPTION" &>/dev/null; then
        log_success "Proxmox summary dashboard notes updated for container $CT_ID"
    else
        log_warn "Failed to update Proxmox summary dashboard notes."
    fi
fi

# Finished
echo ""
echo -e "${GREEN}============================================="
echo "   Frigate Container Updated Successfully!   "
echo "============================================="
echo -e "${NC}"
echo "Container ID:   $CT_ID"
echo "Hostname:       $CT_HOSTNAME"
echo "Image Tag:      $FRIGATE_IMAGE"
echo "Config Path:    $HOST_CONFIG_PATH/config.yml"
echo "Media Path:     $HOST_MEDIA_PATH"
echo ""
echo -e "Web UI & API (Unauthenticated): http://${IP_ADDRESS}:5000"
echo -e "Web UI & API (Recommended):     https://${IP_ADDRESS}:8971"
echo -e "go2rtc Web UI:                  http://${IP_ADDRESS}:1984"
echo ""
echo -e "${YELLOW}NOTE: Port 8971 is the secure (authenticated/TLS) WebUI and API port and is recommended to be used in every case.${NC}"
echo ""
echo "Verify Frigate status using:"
echo "      pct enter $CT_ID"
echo ""
